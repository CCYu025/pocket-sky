#!/usr/bin/env python3
"""beats_raw.json -> cleaned per-beat grid (audio/beats.json) + film-time module variants/beatgrid-B.js
usage: finalize.py LIFT_TIME(song s, a downbeat) FIRST_DOWNBEAT_BEFORE_LIFT_BARS(int) NBEATS"""
import json,sys,os,numpy as np
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)),".."))  # paths are relative to promo/
lift=float(sys.argv[1]);bars_before=int(sys.argv[2]);NB=int(sys.argv[3])
d=json.load(open('audio/beats_raw.json'));T=np.array(d['t_peak']);st=np.array(d['strength'])
n=np.arange(len(T))
li=int(np.argmin(abs(T-lift)));print('lift beat idx',li,T[li])
phase=li%4   # downbeat class
tr=np.array([np.polyval(np.polyfit(n[max(0,i-8):i+9],T[max(0,i-8):i+9],1),i) for i in n])
r=(T-tr)*1000
cls=np.array([np.median(r[(n%4==c)&(st>1.5)]) for c in range(4)])
print('class offsets ms (by idx%4):',np.round(cls,1))
out=T.copy();flag=['']*len(T)
for i in range(len(T)):
    if st[i]<1.5 or abs(r[i]-cls[i%4])>18:
        out[i]=tr[i]+cls[i%4]/1000;flag[i]='interp'
beats=[];start=li-4*bars_before
S=float(out[start])
for k in range(NB):
    i=start+k;beats.append({'m':k,'song':round(float(out[i]),4),'film':round(float(out[i]-S),4),'down':bool(k%4==0),'str':round(float(st[i]),1),'flag':flag[i]})
json.dump({'S':S,'beats':beats},open('audio/beats.json','w'),indent=0)
ib=np.diff([b['film'] for b in beats])
print('S=%.4f  beats %d  ibi mean %.4f (%.2f BPM) min %.3f max %.3f'%(S,NB,ib.mean(),60/ib.mean(),ib.min(),ib.max()))
for k in range(0,NB,4):
    seg=ib[k:k+4];print('bar %2d  m%-3d film %7.3f song %8.3f  BPM %.1f %s'%(k//4,k,beats[k]['film'],beats[k]['song'],60/seg.mean() if len(seg) else 0,' '.join(b['flag'][:1] or '.' for b in beats[k:k+4])))
open('variants/beatgrid-B.js','w').write('/* generated by audio/finalize.py: measured beat grid in FILM time (song time - S). m = beat index, m %% 4 == 0 are bar lines. */\nwindow.BeatGrid = '+json.dumps({'S':round(S,4),'film':[b['film'] for b in beats],'song':[b['song'] for b in beats]})+';\n')
