/**
 * The runtime files that make up the deployed site (and nothing else).
 * Shared by `scripts/build-site.mjs` (the Pages workflow) and its unit test.
 */
import { existsSync } from "node:fs";
import path from "node:path";
import { collect, ROOT } from "./gen-sw-assets.mjs";

/** Files at the site root that are not part of the precache list. */
const EXTRA = ["sw.js", "sw-assets.js", "robots.txt"];

/**
 * @param {string} [root] Source root.
 * @returns {string[]} Sorted paths relative to the root: the shell (index.html, manifest, css/, js/, icons/), `sw.js`,
 *   `sw-assets.js` (generated by the build, so always listed) and `robots.txt` when it exists.
 */
export function siteFiles(root = ROOT) {
  const files = new Set(collect(root).assets);
  for (const f of EXTRA) if (f === "sw-assets.js" || existsSync(path.join(root, f))) files.add(f);
  return [...files].sort();
}
