/**
 * Generate `sw-assets.js`: the precache list and a content hash for the service worker.
 * Usage: `npm run sw` (writes the file; it is generated, git-ignored and rebuilt by `pretest:e2e`, the e2e test server and the Pages workflow).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Top-level files plus directories (recursively) that make up the offline app shell. */
const FILES = ["index.html", "manifest.webmanifest"];
const DIRS = [
  ["css", /./],
  ["js", /\.js$/],
  ["icons", /./],
];

/**
 * @param {string} dir Absolute directory.
 * @param {RegExp} re File-name filter.
 * @param {string} rel Path relative to the site root.
 * @returns {string[]}
 */
function walk(dir, re, rel) {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const r = `${rel}/${e.name}`;
    if (e.isDirectory()) out.push(...walk(path.join(dir, e.name), re, r));
    else if (e.isFile() && re.test(e.name)) out.push(r);
  }
  return out;
}

/**
 * @param {string} [root] Site root.
 * @returns {{assets: string[], version: string}} Sorted asset paths (relative to the root) and the short sha256 of all contents.
 */
export function collect(root = ROOT) {
  const assets = [...FILES, ...DIRS.flatMap(([d, re]) => walk(path.join(root, d), re, d))].sort();
  const h = createHash("sha256");
  for (const a of assets) {
    h.update(a);
    h.update("\0");
    h.update(readFileSync(path.join(root, a)));
    h.update("\0");
  }
  return { assets, version: h.digest("hex").slice(0, 12) };
}

/**
 * @param {string} [root] Site root.
 * @returns {string} Contents of `sw-assets.js`.
 */
export function render(root = ROOT) {
  const { assets, version } = collect(root);
  return [
    "// Generated by scripts/gen-sw-assets.mjs (npm run sw). Do not edit.",
    `self.SW_ASSETS = ${JSON.stringify(assets, null, 2)};`,
    `self.SW_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(ROOT, "sw-assets.js"), render());
  console.log(`sw-assets.js written (${collect().assets.length} assets)`);
}
